import { buildRules, type ChallengeContent, type DayContent } from "./types.js";

const PROOF = "Оцени напряжение до и после практики по шкале от 1 до 10 (например: 6 → 3). Что заметил?";

const SIT = "Сядь на стул, стопы на полу, спина прямая, плечи опущены. Можно лечь на спину.";
const QUIET = "Тихое место, телефон в режим «Не беспокоить», наушники для аудио.";
const SCORE = "Перед началом оцени своё напряжение от 1 до 10 и запомни цифру.";
const AFTER = "После практики снова оцени напряжение и напиши обе цифры в отчёте.";

type Spec = {
  title: string;
  author: string;
  minutes: number;
  intro: string;
  prep?: string[];
  steps: string[];
  beginner: string;
  task: string;
  hint: string;
};

const audio = (n: number) => `/app/audio/breath/day${String(n).padStart(2, "0")}.mp3`;

function build(n: number, s: Spec): DayContent {
  const prep = s.prep ?? [QUIET, SIT, SCORE];
  const description = [
    `Время: ${s.minutes} мин · Методика: ${s.author}`,
    "",
    s.intro,
    "",
    "Подготовка",
    ...prep.map((p, i) => `${i + 1}. ${p}`),
    "",
    "Как выполнять",
    ...s.steps.map((p, i) => `${i + 1}. ${p}`),
    `${s.steps.length + 1}. ${AFTER}`,
    "",
    "Вариант для новичка",
    s.beginner,
    "",
    "Аудиосопровождение (плеер вверху задания) ведёт по шагам: голос подсказывает вдох и выдох, звук отмечает начало и конец.",
  ].join("\n");
  return { title: s.title, description, task: s.task, hint: s.hint, proofType: "text", proofPrompt: PROOF, audioUrl: audio(n) };
}

