import json, os

CTA = 'Напиши «ФОРМА»\nв комментариях'
TOP, SUB_TOP = 0.19, 0.325      # default plate rows (same as the vidIQ renders)
LOW, SUB_LOW = 0.60, 0.735      # lower rows, used where a face/prop sits at the top


def reel(name, tag, scenes, hook, b1, b2, sub, music, ys=(TOP, TOP, TOP, TOP), tag_off=(), sub_y=None):
    """ys = y for hook, beat1, beat2, cta. tag_off = list of (t0, t1) windows without the top tag."""
    yh, y1, y2, yc = ys
    ov = []
    # top tag, split around windows where it would cover a face
    t = 0.0
    for a, b in sorted(tag_off):
        if a > t:
            ov.append(['tag', tag, t, a, 0.105])
        t = b
    if t < 12:
        ov.append(['tag', tag, t, 12.0, 0.105])
    ov += [['hook', hook, 0.0, 3.0, yh],
           ['beat', b1, 3.0, 6.0, y1],
           ['beat', b2, 6.0, 9.0, y2],
           ['cta', CTA, 9.0, 12.0, yc],
           ['sub', sub, 9.0, 12.0, sub_y if sub_y is not None else (SUB_TOP if yc == TOP else SUB_LOW)]]
    return {'name': name, 'scenes': scenes, 'overlays': ov, 'music': music}


