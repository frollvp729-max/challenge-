def sigh(tr: Track, seconds: float, voice_cycles: int = 3) -> Track:
    return tr.paced(SIGH, seconds, voice_cycles=voice_cycles,
                    cycle_labels=[["вдох носом", "ещё", "долгий выдох ртом"]] * voice_cycles)


def count_minute(tr: Track) -> Track:
    tr.say("Сейчас посчитай свои вдохи за одну минуту. Начали.", gap=0.2).bell().pause(57)
    return tr.bell().say("Стоп. Запомни число вдохов.")


