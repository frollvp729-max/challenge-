COUNT = ["раз", "два", "три", "четыре", "пять", "шесть", "семь", "восемь"]


class Voice:
    def __init__(self, model: str):
        from piper import PiperVoice, SynthesisConfig

        self.v = PiperVoice.load(model)
        self.cfg = SynthesisConfig(length_scale=1.18, noise_scale=0.6, noise_w_scale=0.7)
        self.fast = SynthesisConfig(length_scale=1.0, noise_scale=0.6, noise_w_scale=0.7)
        self.cache: dict[tuple[str, bool], np.ndarray] = {}

    def __call__(self, text: str, fast: bool = False) -> np.ndarray:
        key = (text, fast)
        if key not in self.cache:
            chunks = [c.audio_float_array for c in self.v.synthesize(text, syn_config=self.fast if fast else self.cfg)]
            a = np.concatenate(chunks).astype(np.float32)
            a = trim(a)
            peak = float(np.max(np.abs(a))) or 1.0
            self.cache[key] = a / peak * 0.8
        return self.cache[key]


def trim(a: np.ndarray, thr: float = 0.01) -> np.ndarray:
    idx = np.where(np.abs(a) > thr * float(np.max(np.abs(a)) or 1))[0]
    if not len(idx):
        return a
    return a[max(0, idx[0] - 200): idx[-1] + 400]


def sec(n: float) -> int:
    return int(round(n * SR))


def silence(s: float) -> np.ndarray:
    return np.zeros(sec(s), dtype=np.float32)


def tone(s: float, up: bool, vol: float = 0.13) -> np.ndarray:
    """Мягкий тон на вдох (вверх) или выдох (вниз): плавно нарастает и затухает."""
    n = sec(s)
    t = np.arange(n) / SR
    f0, f1 = (174.6, 233.1) if up else (233.1, 174.6)
    f = f0 + (f1 - f0) * (t / s)
    phase = 2 * np.pi * np.cumsum(f) / SR
    wave_ = np.sin(phase) + 0.35 * np.sin(1.5 * phase) + 0.12 * np.sin(2 * phase)
    env = np.sin(np.pi * np.clip(t / s, 0, 1)) ** 1.2
    fade = np.minimum(1, np.minimum(t / 0.25, (s - t) / 0.25))
    return (wave_ * env * fade * vol / 1.47).astype(np.float32)


def bell(vol: float = 0.35, length: float = 3.5) -> np.ndarray:
    t = np.arange(sec(length)) / SR
    out = np.zeros_like(t)
    for ratio, amp, decay in [(1, 1, 1.2), (2.0, 0.45, 0.9), (2.76, 0.3, 0.7), (5.4, 0.12, 0.4)]:
        out += amp * np.sin(2 * np.pi * 528 * ratio * t) * np.exp(-t / decay)
    attack = np.minimum(1, t / 0.005)
    return (out * attack / 1.87 * vol).astype(np.float32)


def tick() -> np.ndarray:
    t = np.arange(sec(0.08)) / SR
    return (np.sin(2 * np.pi * 880 * t) * np.exp(-t / 0.02) * 0.12).astype(np.float32)


def overlay(base: np.ndarray, clip: np.ndarray, at: float, duck: bool = True) -> np.ndarray:
    i = sec(at)
    end = i + len(clip)
    if end > len(base):
        base = np.concatenate([base, np.zeros(end - len(base), dtype=np.float32)])
    if duck:
        base[i:end] *= 0.35
    base[i:end] += clip
    return base


class Track:
    def __init__(self, voice: Voice):
        self.v = voice
        self.parts: list[np.ndarray] = []

    @property
    def t(self) -> float:
        return sum(len(p) for p in self.parts) / SR

    def add(self, a: np.ndarray) -> "Track":
        self.parts.append(a)
        return self

    def say(self, *texts: str, gap: float = 0.7) -> "Track":
        for text in texts:
            self.add(self.v(text)).add(silence(gap))
        return self

    def pause(self, s: float) -> "Track":
        return self.add(silence(s))

    def bell(self) -> "Track":
        return self.add(bell())

    def free(self, seconds: float, prompts: list[tuple[float, str]] = (), bells: list[float] = ()) -> "Track":
        """Тишина заданной длины с подсказками голосом и колокольчиками в нужные секунды."""
        a = silence(seconds)
        for at, text in prompts:
            a = overlay(a, self.v(text), at, duck=False)
        for at in bells:
            a = overlay(a, bell(0.25), at, duck=False)
        return self.add(a[: max(len(a), sec(seconds))])

    def paced(
        self,
        pattern: list[tuple[str, float]],
        seconds: float,
        voice_cycles: int = 2,
        labels: dict[str, str] | None = None,
        cycle_labels: list[list[str]] | None = None,
        prompts: list[tuple[float, str]] = (),
        last_minute: bool = True,
    ) -> "Track":
        """
        Ритм дыхания. pattern — фазы вида ("in", 4), ("hold", 7), ("out", 8).
        Первые voice_cycles кругов голос называет фазу и считает секунды, дальше ведут тоны.
        prompts — подсказки (секунда от начала блока, текст), ставятся на начало ближайшего выдоха.
        """
        names = {"in": "вдох", "out": "выдох", "hold": "пауза", **(labels or {})}
        cycle = sum(d for _, d in pattern)
        n = max(1, round(seconds / cycle))
        a = np.zeros(0, dtype=np.float32)
        exhale_starts: list[float] = []
        voiced: list[tuple[float, np.ndarray]] = []
        for c in range(n):
            for k, (ph, d) in enumerate(pattern):
                start = len(a) / SR
                seg = tone(d, True) if ph == "in" else tone(d, False) if ph == "out" else silence(d)
                if ph == "hold":
                    seg = silence(d)
                a = np.concatenate([a, seg])
                if ph == "out":
                    exhale_starts.append(start)
                if c < voice_cycles:
                    label = cycle_labels[c][k] if cycle_labels and c < len(cycle_labels) else names[ph]
                    voiced.append((start + 0.05, self.v(label, fast=True)))
                    if d >= 3 and not cycle_labels:
                        for s in range(1, int(d)):
                            voiced.append((start + s + 0.05, self.v(COUNT[s], fast=True)))
        for at, clip in voiced:
            a = overlay(a, clip, at)
        extra = list(prompts)
        total = len(a) / SR
        if last_minute and total >= 240:
            extra.append((total - 62, "Осталась одна минута."))
        for at, text in extra:
            later = [s for s in exhale_starts if s >= at]
            pos = later[0] if later else at
            a = overlay(a, self.v(text), pos + 0.1)
        return self.add(a)

    def breath478(self, cycles: int = 4) -> "Track":
        """4–7–8 по Эндрю Вейлу: голос считает каждый круг."""
        self.say("Кончик языка поставь за верхние передние зубы.", "Полностью выдохни ртом со звуком у-ух.")
        self.pause(1.5)
        for c in range(cycles):
            self.paced(
                [("in", 4), ("hold", 7), ("out", 8)],
                19,
                voice_cycles=1,
                labels={"in": "вдох носом", "hold": "задержка", "out": "выдох ртом"},
                last_minute=False,
            )
        return self.pause(2)

    def counter(self, max_s: int = 45) -> "Track":
        """Контрольная пауза: тик каждую секунду, голос каждые 5 секунд."""
        a = silence(max_s + 1)
        for s in range(1, max_s + 1):
            clip = self.v(str_num(s), fast=True) if s % 5 == 0 else tick()
            a = overlay(a, clip, s, duck=False)
        return self.add(a)

    def render(self) -> np.ndarray:
        a = np.concatenate(self.parts)
        return np.clip(a, -1, 1)


