def write_mp3(a: np.ndarray, path: Path) -> None:
    with tempfile.NamedTemporaryFile(suffix=".wav") as tmp:
        with wave.open(tmp.name, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((a * 32767).astype(np.int16).tobytes())
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp.name, "-ac", "1", "-ar", str(SR),
                        "-codec:a", "libmp3lame", "-b:a", "24k", str(path)], check=True)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--days", default="")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    v = Voice(args.voice)
    tracks = day_tracks(v)
    wanted = {int(x) for x in args.days.split(",") if x} or set(tracks)
    for n in sorted(wanted):
        a = tracks[n].render()
        path = out / f"day{n:02d}.mp3"
        write_mp3(a, path)
        print(f"day{n:02d}: {len(a) / SR / 60:.1f} мин, {path.stat().st_size // 1024} КБ")


if __name__ == "__main__":
    main()
